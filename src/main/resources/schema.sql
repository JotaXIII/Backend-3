CREATE TABLE IF NOT EXISTS transacciones_procesadas (
 ejecucion_id BIGINT NOT NULL, id BIGINT NOT NULL, fecha DATE NOT NULL,
 monto NUMERIC(18,2) NOT NULL, tipo VARCHAR(20) NOT NULL, anomalia BOOLEAN NOT NULL,
 PRIMARY KEY(ejecucion_id,id)
);
CREATE TABLE IF NOT EXISTS resumen_transacciones (
 ejecucion_id BIGINT NOT NULL, fecha DATE NOT NULL, tipo VARCHAR(20) NOT NULL,
 cantidad BIGINT NOT NULL, monto_total NUMERIC(18,2) NOT NULL, anomalias BIGINT NOT NULL,
 PRIMARY KEY(ejecucion_id,fecha,tipo)
);
CREATE TABLE IF NOT EXISTS intereses_calculados (
 ejecucion_id BIGINT NOT NULL, cuenta_id BIGINT NOT NULL, nombre VARCHAR(150) NOT NULL,
 saldo_inicial NUMERIC(18,2) NOT NULL, edad INTEGER NOT NULL, tipo VARCHAR(20) NOT NULL,
 tasa NUMERIC(8,6) NOT NULL, interes NUMERIC(18,2) NOT NULL, saldo_final NUMERIC(18,2) NOT NULL,
 PRIMARY KEY(ejecucion_id,cuenta_id)
);
CREATE TABLE IF NOT EXISTS movimientos_anuales (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ejecucion_id BIGINT NOT NULL,
 cuenta_id BIGINT NOT NULL, fecha DATE NOT NULL, transaccion VARCHAR(20) NOT NULL,
 monto NUMERIC(18,2) NOT NULL, descripcion VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS estados_cuenta_anuales (
 ejecucion_id BIGINT NOT NULL, cuenta_id BIGINT NOT NULL, anio INTEGER NOT NULL,
 cantidad_movimientos BIGINT NOT NULL, total_depositos NUMERIC(18,2) NOT NULL,
 total_cargos NUMERIC(18,2) NOT NULL, saldo_anual NUMERIC(18,2) NOT NULL,
 PRIMARY KEY(ejecucion_id,cuenta_id,anio)
);
CREATE TABLE IF NOT EXISTS registros_rechazados (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ejecucion_id BIGINT NOT NULL,
 job VARCHAR(80) NOT NULL, etapa VARCHAR(30) NOT NULL, datos VARCHAR(1000) NOT NULL,
 motivo VARCHAR(500) NOT NULL, fecha_rechazo TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS publicaciones_batch (
 job VARCHAR(80) PRIMARY KEY, ejecucion_id BIGINT NOT NULL,
 publicada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
