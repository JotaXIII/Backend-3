CREATE TABLE IF NOT EXISTS pagos (
 id VARCHAR(80) PRIMARY KEY, cliente_id BIGINT NOT NULL,
 tipo VARCHAR(20) NOT NULL, origen BIGINT, destino BIGINT, monto NUMERIC(18,2) NOT NULL,
 estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE', intentos INTEGER NOT NULL DEFAULT 0,
 creada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS outbox (
 id VARCHAR(100) PRIMARY KEY, topico VARCHAR(80) NOT NULL, contenido TEXT NOT NULL,
 publicada BOOLEAN NOT NULL DEFAULT FALSE, creada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS eventos_recibidos (
 id VARCHAR(100) PRIMARY KEY, topico VARCHAR(80) NOT NULL, contenido TEXT NOT NULL,
 recibida TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
