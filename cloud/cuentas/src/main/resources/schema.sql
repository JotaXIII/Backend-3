CREATE TABLE IF NOT EXISTS cuentas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cliente_id BIGINT NOT NULL, tipo VARCHAR(20) NOT NULL, alias VARCHAR(80) NOT NULL DEFAULT '',
 saldo NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK(saldo >= 0),
 estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVA', moneda VARCHAR(3) NOT NULL DEFAULT 'CLP'
);
CREATE TABLE IF NOT EXISTS movimientos (
 id VARCHAR(80) PRIMARY KEY, cliente_id BIGINT NOT NULL, tipo VARCHAR(20) NOT NULL,
 origen BIGINT, destino BIGINT, monto NUMERIC(18,2) NOT NULL,
 creada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
