CREATE TABLE IF NOT EXISTS clientes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
 nombre VARCHAR(150) NOT NULL, email VARCHAR(180) NOT NULL UNIQUE,
 telefono VARCHAR(40) NOT NULL, activo BOOLEAN NOT NULL DEFAULT TRUE
);
